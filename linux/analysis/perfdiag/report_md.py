"""Markdown report with PNG charts, for pasting into tickets and wikis."""

import os

from . import findings
from .report_common import (catalogue_for, charts_for, coverage_lines, evidence_rows, generated_by,
                            header_facts, kernel_hypotheses, layout_facts, settings_rows, summary_hypotheses,
                            time_above_rows)
from .timeutil import stamp_minutes


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def md_table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(cell(item) for item in row) + " |")
    return "\n".join(lines)


def finding_markdown(result, hypothesis, catalogue, shown, chart_dir, full):
    sections = findings.hypothesis_sections(result, hypothesis)
    headline = "%s %s — %s — confidence %s" % (
        hypothesis.id, hypothesis.title, findings.subject_label(result, hypothesis), hypothesis.confidence)
    lines = ["### " + headline, ""]
    lines.extend(sections["summary"])
    lines.extend(sections["related"])
    if sections["supporting"]:
        lines.append("**Supporting:** " + "; ".join(sections["supporting"]) + ".")
    if sections["against"]:
        lines.append("**Against:** " + "; ".join(sections["against"]) + ".")
    lines.extend(sections["processes"])
    for line in sections["not_seen"]:
        lines.append("**Not seen:** " + line)
    if not full:
        return "\n\n".join(item for item in ("\n".join(lines),) if item) + "\n"
    rows = evidence_rows(result, hypothesis)
    if rows:
        lines.extend(["", md_table(["Role", "Indicator", "Device", "Window", "Duration", "Mean", "Peak", "Score"], rows)])
    if sections["kernel"]:
        lines.extend(["", "Kernel log events in this window:", ""])
        lines.extend("- `%s`" % line.replace("`", "'") for line in sections["kernel"])
    for name in charts_for(result, hypothesis, catalogue):
        if name in shown:
            continue
        shown.add(name)
        title = next(chart.title for chart in catalogue if chart.name == name)
        lines.extend(["", "![%s](%s/%s.png)" % (title, chart_dir, name)])
    lines.extend(["", "**Next steps**", ""])
    lines.extend("- " + step for step in hypothesis.next_steps)
    return "\n".join(lines) + "\n"


def host_markdown(result, charts_directory, chart_dir="charts"):
    """(markdown text, [png paths written])."""
    host = result.host
    zone = host.zone
    catalogue = catalogue_for(result)
    written = []

    def ensure_chart(name):
        chart = next(item for item in catalogue if item.name == name)
        path = os.path.join(charts_directory, name + ".png")
        if path not in written:
            os.makedirs(charts_directory, exist_ok=True)
            with open(path, "wb") as handle:
                handle.write(chart.render("png"))
            written.append(path)

    lines = ["# Performance diagnosis: %s" % host.host, "", "Generated by %s." % generated_by(), ""]
    lines.extend("- **%s:** %s" % (key, value) for key, value in header_facts(result))
    lines.extend(["", "## Summary", ""])
    summary = summary_hypotheses(result)
    if summary:
        for hypothesis in summary:
            lines.append(finding_markdown(result, hypothesis, catalogue, set(), chart_dir, full=False))
    else:
        lines.append("No hypothesis was raised: no sustained episode on a primary indicator in this window.")
    from_kernel = kernel_hypotheses(result)
    if from_kernel:
        lines.extend(["", "### Kernel log findings", "", "Raised by kernel log events alone; not ranked against the "
                      "measured hypotheses.", ""])
        for hypothesis in from_kernel:
            lines.append(finding_markdown(result, hypothesis, catalogue, set(), chart_dir, full=False))

    lines.extend(["", "## Indicator timeline", ""])
    if any(chart.name == "timeline" for chart in catalogue):
        ensure_chart("timeline")
        lines.append("![Indicator timeline](%s/timeline.png)" % chart_dir)
    else:
        lines.append("No sustained indicator and no impactful transient.")

    lines.extend(["", "## Findings", ""])
    shown = {"timeline"}
    if result.hypotheses:
        for hypothesis in result.hypotheses:
            for name in charts_for(result, hypothesis, catalogue):
                ensure_chart(name)
            lines.append(finding_markdown(result, hypothesis, catalogue, shown, chart_dir, full=True))
    else:
        lines.append("None.")

    lines.extend(["", "## Transient events", ""])
    if result.impactful:
        rows = [(e.id, e.rule, e.device or "-", stamp_minutes(e.start, zone), findings.duration_text(e.duration_s),
                 "; ".join(e.evidence)) for e in result.impactful]
        lines.append(md_table(["Id", "Indicator", "Device", "Start", "Duration", "Evidence"], rows))
    else:
        lines.append("No impactful transients.")
    for line in result.transient_summaries:
        lines.append("")
        lines.append("Repeated: %s." % line)
    if result.absorbed:
        lines.extend(["", "Absorbed transients: %d." % sum(result.absorbed.values()), "",
                      md_table(["Indicator", "Absorbed bursts"], sorted(result.absorbed.items()))])

    lines.extend(["", "## Time above threshold", ""])
    rows = time_above_rows(result)
    lines.append(md_table(["Indicator", "Role", "Past warn", "Past crit", "Median", "Tail", "Extreme", "Fires when"], rows)
                 if rows else "No indicators were evaluated.")

    lines.extend(["", "## Host and storage layout", ""])
    layout = layout_facts(host)
    if layout is None:
        lines.append("No hardware inventory in the bundle.")
    else:
        facts, disks, mounts = layout
        lines.extend("- **%s:** %s" % (key, value) for key, value in facts)
        lines.extend(["", md_table(["Device", "Kernel name", "Class", "Size", "Model", "Parallelism", "Built on"], disks)])
        if mounts:
            lines.extend(["", md_table(["Mount point", "Type", "Block device"], mounts)])

    lines.extend(["", "## Data coverage and limits", ""])
    lines.extend("- " + line for line in coverage_lines(result))
    lines.extend(["", "## Analysis settings", "", md_table(["Setting", "Value", "Source"], settings_rows(result)), ""])
    return "\n".join(lines), written
